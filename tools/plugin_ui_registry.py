#!/usr/bin/env python3
"""Load the plugin UI registry and emit the C++ tables the device renderer validates against.

`schema/plugin_ui_registry.json` is the single source of truth for widgets, properties,
style tokens, events, actions, bindings and limits. The XML compiler reads it directly; the
device firmware generates its validator header from it with `--output` (and `--check` in CI).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTRY_PATH = ROOT / "schema" / "plugin_ui_registry.json"


def load_registry(path: Path = REGISTRY_PATH) -> dict:
    registry = json.loads(path.read_text(encoding="utf-8"))
    widgets = registry["widgets"]
    for binding in registry["bindings"]:
        if binding["widget"] not in widgets:
            raise ValueError(f"binding references unknown widget {binding['widget']}")
    names = registry.get("color_token_names", {})
    if set(names.values()) != set(registry["color_tokens"]) or len(names) != len(registry["color_tokens"]):
        raise ValueError("color_token_names must name every color token exactly once")
    shared = set(registry["int_props"]) | set(registry["color_props"])
    for name, spec in widgets.items():
        if shared & set(spec["props"]):
            raise ValueError(f"widget {name} redeclares a shared property")
    return registry


def _c_string(value: str) -> str:
    return json.dumps(value)


def _c_ident(value: str) -> str:
    return "".join(part.capitalize() for part in value.replace(".", "_").split("_"))


def render_header(registry: dict) -> str:
    limits = registry["limits"]
    lines = [
        "// Generated by aitbase-vision-plugin-sdk tools/plugin_ui_registry.py from schema/plugin_ui_registry.json. Do not edit.",
        "#ifndef PLUGIN_UI_REGISTRY_GENERATED_H",
        "#define PLUGIN_UI_REGISTRY_GENERATED_H",
        "",
        "#include <cstddef>",
        "",
        "namespace plugin_ui_registry {",
        "",
        f"constexpr const char *kFormat = {_c_string(registry['format'])};",
        f"constexpr int kVersion = {registry['version']};",
    ]
    for key, value in limits.items():
        lines.append(f"constexpr size_t k{_c_ident(key)} = {value};")
    lines += [
        "",
        "struct IntProp {",
        "    const char *name;",
        "    int min;",
        "    int max;",
        "};",
        "",
        "struct WidgetSpec {",
        "    const char *name;",
        "    const char *const *props;",
        "    size_t prop_count;",
        "    bool children;",
        "    bool requires_action;",
        "};",
        "",
        "struct BindingSpec {",
        "    const char *widget;",
        "    const char *property;",
        "    const char *key;",
        "    const char *type;",
        "};",
        "",
        "static const IntProp kIntProps[] = {",
    ]
    for name, (low, high) in registry["int_props"].items():
        lines.append(f"    {{{_c_string(name)}, {low}, {high}}},")
    lines.append("};")

    def string_table(name: str, values: list[str]) -> None:
        lines.append(f"static const char *const {name}[] = {{")
        lines.extend(f"    {_c_string(value)}," for value in values)
        lines.append("};")

    string_table("kColorProps", registry["color_props"])
    string_table("kColorTokens", registry["color_tokens"])
    string_table("kEvents", registry["events"])
    string_table("kActions", registry["actions"])
    for name, spec in registry["widgets"].items():
        if spec["props"]:
            string_table(f"k{_c_ident(name)}Props", spec["props"])
    lines.append("static const WidgetSpec kWidgets[] = {")
    for name, spec in registry["widgets"].items():
        props = f"k{_c_ident(name)}Props" if spec["props"] else "nullptr"
        count = len(spec["props"])
        lines.append(
            f"    {{{_c_string(name)}, {props}, {count}, {str(spec['children']).lower()}, "
            f"{str(spec['requires_action']).lower()}}},")
    lines.append("};")
    lines.append("static const BindingSpec kBindings[] = {")
    for binding in registry["bindings"]:
        fields = ", ".join(_c_string(binding[key]) for key in ("widget", "property", "key", "type"))
        lines.append(f"    {{{fields}}},")
    lines += ["};", "", "}  // namespace plugin_ui_registry", "", "#endif", ""]
    return "\n".join(lines)


def render_globals(registry: dict) -> str:
    """Platform globals in LVGL XML form: color tokens as <consts>, binding keys as <subjects>.

    Plugin UI references them as style_bg_color="#surface" and bind_text="title". Plugins cannot
    add their own colors or subjects; the compiler resolves only these names.
    """
    lines = [
        "<!-- Generated by tools/plugin_ui_registry.py from schema/plugin_ui_registry.json. Do not edit. -->",
        "<globals>",
        "  <consts>",
    ]
    for name, value in registry["color_token_names"].items():
        lines.append(f'    <color name="{name}" value="0x{value[1:]}"/>')
    lines += ["  </consts>", "  <subjects>"]
    seen = set()
    for binding in registry["bindings"]:
        if binding["key"] not in seen:
            seen.add(binding["key"])
            lines.append(f'    <{binding["type"]} name="{binding["key"]}" value=""/>')
    lines += ["  </subjects>", "</globals>", ""]
    return "\n".join(lines)


def _write_or_check(path: Path, content: str, check: bool) -> int:
    if check:
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            print(f"{path} is stale; regenerate it with tools/plugin_ui_registry.py", file=sys.stderr)
            return 1
        return 0
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", type=Path, default=REGISTRY_PATH, help="registry JSON to read")
    parser.add_argument("--output", type=Path, help="device C++ validator header to write or check")
    parser.add_argument("--globals", type=Path, help="platform globals.xml to write or check")
    parser.add_argument("--check", action="store_true", help="fail if outputs are stale instead of writing them")
    args = parser.parse_args(argv)
    if not args.output and not args.globals:
        parser.error("pass --output and/or --globals")
    registry = load_registry(args.registry)
    rc = 0
    if args.output:
        rc |= _write_or_check(args.output, render_header(registry), args.check)
    if args.globals:
        rc |= _write_or_check(args.globals, render_globals(registry), args.check)
    return rc

if __name__ == "__main__":
    raise SystemExit(main())
